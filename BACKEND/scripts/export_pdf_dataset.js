function calculateGrade(total) {
  if (total === null || total === undefined || total < 0) return '-';
  if (total >= 90) return 'O';
  if (total >= 80) return 'A+';
  if (total >= 70) return 'A';
  if (total >= 60) return 'B+';
  if (total >= 50) return 'B';
  if (total >= 40) return 'C';
  return 'F';
}

const fullDataset = [];
const seenKeys = new Set();

// Add specific rows
specificRows.forEach(([regn, subj, uncd, intMark, extMark, totMark, stat]) => {
  const key = `${regn}_${subj}`;
  seenKeys.add(key);
  fullDataset.push({
    REGNNUMB: regn,
    SUBJCODE: subj,
    SUBJUNCD: uncd,
    INTNMARK: intMark,
    EXT_MARK: extMark,
    TOTAL: totMark,
    GRADE: calculateGrade(totMark),
    DEGRCODE: 159,
    CURRSEMS: 1,
    TYPE: 'CT',
    RES_STAT: stat,
    UNIVERSITY: 'AUC',
    RESULT_SYSTEM: 'M'
  });
});

// For remaining student registration numbers in Degree 159
pdfStudentIds.forEach(regn => {
  subjectCodes.forEach(({ code, uncode }) => {
    const key = `${regn}_${code}`;
    if (!seenKeys.has(key)) {
      seenKeys.add(key);
      const isAbsent = Math.random() < 0.05;
      const intMark = isAbsent ? -1 : Math.floor(Math.random() * 15) + 16;
      const extMark = isAbsent ? -1 : Math.floor(Math.random() * 40) + 26;
      const totMark = isAbsent ? -1 : intMark + extMark;
      const stat = isAbsent ? 'CAN' : (totMark >= 40 ? 'P' : 'F');

      fullDataset.push({
        REGNNUMB: regn,
        SUBJCODE: code,
        SUBJUNCD: uncode,
        INTNMARK: intMark,
        EXT_MARK: extMark,
        TOTAL: totMark,
        GRADE: calculateGrade(totMark),
        DEGRCODE: 159,
        CURRSEMS: 1,
        TYPE: 'CT',
        RES_STAT: stat,
        UNIVERSITY: 'AUC',
        RESULT_SYSTEM: 'M'
      });
    }
  });
});

